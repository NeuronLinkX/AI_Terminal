#!/usr/bin/env node
'use strict';
// Refreshes the download site (site/) from the real build: version, file names, sizes and SHA-256 of the DMG / ZIP in dist/.
//   node scripts/build-site.js                       links point at the GitHub Release of this version
//   node scripts/build-site.js --local               also copies the files to site/downloads/ and links them relatively
//   node scripts/build-site.js --base https://host/downloads   links point at <base>/<file> (the files are uploaded there by you)
//   --dmg-only        no ZIP on the page (and none copied)        --shots <dir>   copy the PNG screenshots of <dir> into site/assets/img
//   --shots-ko <dir>  the same for the Korean edition (site/assets/img/ko)
// Preview:  cd site && python3 -m http.server 8080
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const site = path.join(root, 'site');
const argv = process.argv.slice(2);
const flag = (n) => argv.includes(n);
const opt = (n) => { const i = argv.indexOf(n); return i >= 0 ? argv[i + 1] : ''; };
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const local = flag('--local');
const base = (opt('--base') || (local ? 'downloads' : '')).replace(/\/$/, '');
const repo = String(pkg.homepage || '').replace(/\/$/, '');
const version = pkg.version;
const product = (pkg.build && pkg.build.productName) || pkg.productName;

const sha256 = (file) => new Promise((resolve, reject) => {
  const h = crypto.createHash('sha256');
  fs.createReadStream(file).on('data', (d) => h.update(d)).on('end', () => resolve(h.digest('hex'))).on('error', reject);
});
const ymd = (d) => `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;

(async () => {
  const files = {};
  let newest = 0;
  for (const [key, ext] of [['dmg', 'dmg'], ['zip', 'zip']]) {
    if (key === 'zip' && flag('--dmg-only')) continue;
    const name = `${product}-${version}-arm64.${ext}`;
    const file = path.join(root, 'dist', name);
    if (!fs.existsSync(file)) { console.log(`! ${name} is not in dist/, run npm run dist first`); continue; }
    const st = fs.statSync(file);
    newest = Math.max(newest, st.mtimeMs);
    const url = base ? `${base}/${name}` : `${repo}/releases/download/v${version}/${name}`;
    if (local) {
      fs.mkdirSync(path.join(site, 'downloads'), { recursive: true });
      fs.copyFileSync(file, path.join(site, 'downloads', name));
    }
    files[key] = { name, size: st.size, sha256: await sha256(file), url };
    console.log(`✓ ${name}  ${(st.size / 1e6).toFixed(1)} MB  ${files[key].sha256}`);
  }
  const release = { version, date: ymd(newest ? new Date(newest) : new Date()), minMacOS: '13', repo, releases: `${repo}/releases`, files };
  fs.writeFileSync(path.join(site, 'assets', 'js', 'release.js'), `/* Generated by scripts/build-site.js. Do not edit by hand. */\nwindow.MACAITERM_RELEASE = ${JSON.stringify(release)};\n`);

  const img = path.join(site, 'assets', 'img');
  fs.mkdirSync(img, { recursive: true });
  const shots = opt('--shots');
  if (shots) for (const f of fs.readdirSync(shots).filter((x) => /\.png$/i.test(x))) fs.copyFileSync(path.join(shots, f), path.join(img, f));
  const shotsKo = opt('--shots-ko'); // Korean edition (site/ko/) uses its own images: assets/img/ko/
  if (shotsKo) { fs.mkdirSync(path.join(img, 'ko'), { recursive: true }); for (const f of fs.readdirSync(shotsKo).filter((x) => /\.png$/i.test(x))) fs.copyFileSync(path.join(shotsKo, f), path.join(img, 'ko', f)); }
  fs.copyFileSync(path.join(root, 'build', 'icon.png'), path.join(img, 'icon.png'));
  fs.writeFileSync(path.join(site, '.nojekyll'), '');
  console.log(`✓ site refreshed, download links: ${base ? base + '/…' : 'GitHub Release v' + version}${shots ? ' · screenshots from ' + shots : ''}${shotsKo ? ' · Korean screenshots from ' + shotsKo : ''}`);
})();
