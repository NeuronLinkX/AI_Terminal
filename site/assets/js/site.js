/* MacAIterm site: light / dark switch, copy buttons, release data. No network requests, no tracking. */
(() => {
  const root = document.documentElement;
  const store = {
    get(k) { try { return localStorage.getItem(k); } catch { return null; } },
    set(k, v) { try { localStorage.setItem(k, v); } catch { /* storage may be blocked */ } },
  };
  const saved = store.get('macaiterm.theme');
  if (saved === 'light' || saved === 'dark') root.dataset.theme = saved; // otherwise the system setting decides
  const current = () => root.dataset.theme || (matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light');

  document.addEventListener('DOMContentLoaded', () => {
    const tb = document.getElementById('theme');
    if (tb) tb.onclick = () => { const n = current() === 'dark' ? 'light' : 'dark'; root.dataset.theme = n; store.set('macaiterm.theme', n); };

    document.querySelectorAll('.copy').forEach((b) => {
      b.onclick = async () => {
        const text = b.dataset.copy || (b.parentElement.firstChild.textContent || '').trim();
        try { await navigator.clipboard.writeText(text); } catch { const r = document.createRange(); r.selectNodeContents(b.parentElement.firstChild); const s = getSelection(); s.removeAllRanges(); s.addRange(r); document.execCommand('copy'); s.removeAllRanges(); }
        const old = b.textContent;
        b.textContent = root.lang === 'ko' ? '복사됨' : 'Copied';
        setTimeout(() => { b.textContent = old; }, 1400);
      };
    });

    // release data (assets/js/release.js is generated by scripts/build-site.js)
    const R = window.MACAITERM_RELEASE;
    if (R) {
      const fmt = (n) => (n >= 1e6 ? `${(n / 1e6).toFixed(0)} MB` : `${Math.round(n / 1e3)} KB`);
      const pick = (path) => path.split('.').reduce((o, k) => (o == null ? o : o[k]), R);
      document.querySelectorAll('[data-rel]').forEach((e) => {
        const v = pick(e.dataset.rel);
        if (v != null) e.textContent = e.dataset.rel.endsWith('size') ? fmt(v) : v;
      });
      // pages in a sub folder (ko/) reach site-relative download links one level up
      const up = (u) => (root.dataset.depth && !/^(?:[a-z][a-z0-9+.-]*:|\/)/i.test(u) ? '../' + u : u);
      document.querySelectorAll('[data-rel-href]').forEach((e) => { const v = pick(e.dataset.relHref); if (v) e.setAttribute('href', up(v)); });
      document.querySelectorAll('[data-rel-copy]').forEach((e) => { const v = pick(e.dataset.relCopy); if (v) e.dataset.copy = v; });
      document.querySelectorAll('[data-needs]').forEach((e) => { if (!pick(e.dataset.needs)) e.remove(); }); // e.g. no ZIP in this build
    }
  });
})();

// The footer remains a complete navigation fallback when JavaScript is unavailable.
document.addEventListener('DOMContentLoaded', () => {
  const toggle = document.querySelector('.menu-toggle');
  const menu = document.getElementById('mobile-nav');
  if (!toggle || !menu) return;
  toggle.hidden = false;
  const close = () => { menu.hidden = true; toggle.setAttribute('aria-expanded', 'false'); };
  toggle.addEventListener('click', () => {
    const open = toggle.getAttribute('aria-expanded') !== 'true';
    toggle.setAttribute('aria-expanded', String(open));
    menu.hidden = !open;
  });
  document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape' && !menu.hidden) { close(); toggle.focus(); }
  });
  menu.addEventListener('click', (event) => { if (event.target.closest('a')) close(); });
  matchMedia('(min-width: 921px)').addEventListener('change', (event) => { if (event.matches) close(); });
});

// Demo video in the hero: muted and looping, with a pause / play button; it does not start by itself for visitors who prefer reduced motion.
document.addEventListener('DOMContentLoaded', () => {
  const v = document.getElementById('demo');
  const b = document.getElementById('demo-toggle');
  if (!v || !b) return;
  const ko = document.documentElement.lang === 'ko';
  const text = { pause: ko ? '영상 일시정지' : 'Pause the video', play: ko ? '영상 재생' : 'Play the video' };
  const sync = () => { const playing = !v.paused; b.textContent = playing ? '❚❚' : '▶'; b.setAttribute('aria-label', playing ? text.pause : text.play); };
  if (matchMedia('(prefers-reduced-motion: reduce)').matches) { v.removeAttribute('autoplay'); v.pause(); }
  b.hidden = false;
  b.addEventListener('click', () => { if (v.paused) v.play().catch(() => {}); else v.pause(); });
  v.addEventListener('play', sync); v.addEventListener('pause', sync);
  sync();
});
