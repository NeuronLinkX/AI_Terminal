'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');
const on = (ch, cb) => {
  const h = (_e, p) => cb(p);
  ipcRenderer.on(ch, h);
  return () => ipcRenderer.removeListener(ch, h);
};
const call = (ch, arg) => ipcRenderer.invoke(ch, arg);

contextBridge.exposeInMainWorld('ait', {
  // terminal / panes
  ptyInput: (id, d) => ipcRenderer.send('pty:input', { id, d }),
  ptyResize: (id, cols, rows) => ipcRenderer.send('pty:resize', { id, cols, rows }),
  onPtyData: (cb) => on('pty:data', cb),
  onPtyState: (cb) => on('pty:state', cb),
  onPtyExit: (cb) => on('pty:exit', cb),
  snapshot: (id) => call('pty:snapshot', id),
  info: () => call('app:info'),
  restore: () => call('app:restore'),
  tabNew: (fromId, cwd) => call('tab:new', { fromId, cwd }),
  tabClose: (id) => call('tab:close', id),
  tabActive: (id) => ipcRenderer.send('tab:active', id),
  paneNew: (tabId) => call('pane:new', tabId),
  paneClose: (tabId, paneId) => call('pane:close', { tabId, paneId }),
  // command blocks
  onBlockStart: (cb) => on('block:start', cb),
  onBlockEnd: (cb) => on('block:end', cb),
  // AI
  aiSubmit: (id, text, plan) => ipcRenderer.send('ai:submit', { id, text, plan: !!plan }),
  aiAbort: (id) => ipcRenderer.send('ai:abort', id),
  approve: (tab, id, approved, extra = {}) => ipcRenderer.send('ai:approval', { tab, id, approved, ...extra }),
  onAiEvent: (cb) => on('ai:event', cb),
  permGet: (id) => call('perm:get', id),
  permSet: (id, mode) => call('perm:set', { id, mode }),
  permRemove: (id, key) => call('perm:remove', { id, key }),
  onPermState: (cb) => on('perm:state', cb),
  remoteSet: (id, on_) => call('remote:set', { id, on: on_ }),
  sshGet: (id) => call('ssh:get', id),
  // session manager
  sessList: () => call('sess:list'),
  sessSave: (s) => call('sess:save', s),
  sessDelete: (id) => call('sess:delete', id),
  sessDuplicate: (id) => call('sess:duplicate', id),
  sessFromConfig: (alias) => call('sess:from-config', alias),
  sessCommand: (arg) => call('sess:command', arg),
  // file panel (server over ssh, and this Mac)
  sftpHome: (id) => call('sftp:home', id),
  sftpList: (id, p) => call('sftp:list', { id, path: p }),
  sftpMkdir: (id, p) => call('sftp:mkdir', { id, path: p }),
  sftpRename: (id, from, to) => call('sftp:rename', { id, from, to }),
  sftpRemove: (id, p) => call('sftp:remove', { id, path: p }),
  sftpChmod: (id, p, mode) => call('sftp:chmod', { id, path: p, mode }),
  sftpPreview: (id, p) => call('sftp:preview', { id, path: p }),
  sftpUpload: (id, local, remoteDir, mode) => call('sftp:upload', { id, local, remoteDir, mode }),
  sftpDownload: (id, remote, localDir, mode) => call('sftp:download', { id, remote, localDir, mode }),
  sftpCancel: (id, xid) => call('sftp:cancel', { id, xid }),
  sftpTransfers: (id) => call('sftp:transfers', id),
  sftpClear: (id) => call('sftp:clear', id),
  sftpDragPrepare: (id, remote) => call('sftp:drag-prepare', { id, remote }),
  dragStart: (file) => ipcRenderer.send('drag:start', file),
  onTransfer: (cb) => on('sftp:transfer', cb),
  localList: (p) => call('local:list', p),
  localMkdir: (p) => call('local:mkdir', p),
  localRename: (from, to) => call('local:rename', { from, to }),
  localTrash: (p) => call('local:trash', p),
  localReveal: (p) => ipcRenderer.send('local:reveal', p),
  pathForFile: (f) => { try { return webUtils.getPathForFile(f); } catch { return ''; } }, // a file dropped from Finder
  onSshState: (cb) => on('ssh:state', cb),
  onSshMetrics: (cb) => on('ssh:metrics', cb),
  onSshProblem: (cb) => on('ssh:problem', cb),
  onSshOffer: (cb) => on('ssh:offer', cb),
  classify: (t) => call('shell:classify', t),
  shellRun: (id, text) => call('shell:run', { id, text }),
  resetSession: (id) => call('session:reset', id),
  undoFile: (tab, id) => call('file:undo', { tab, id }),
  // settings / secrets
  settingsGet: () => call('settings:get'),
  settingsSet: (key, value) => call('settings:set', { key, value }),
  settingsReset: () => call('settings:reset'),
  onSettings: (cb) => on('settings:changed', cb),
  secretSet: (name, value) => call('secret:set', { name, value }),
  usageGet: () => call('usage:get'),
  usageOfficial: () => call('usage:official'),
  onUsage: (cb) => on('usage:update', cb),
  // models / onboarding
  llmStatus: () => call('llm:status'),
  kvInfo: () => call('kv:info'),
  llmDetect: () => call('llm:detect'),
  llmPrefer: (id) => call('llm:prefer', id),
  llmSetModel: (name, provider) => call('llm:setModel', { name, provider }),
  onLlmStatus: (cb) => on('llm:status', cb),
  onboardStatus: () => call('onboard:status'),
  onboardPull: (name) => call('onboard:pull', name),
  onboardAbort: () => ipcRenderer.send('onboard:abort'),
  onOnboardProgress: (cb) => on('onboard:progress', cb),
  // history / audit
  historyList: () => call('history:list'),
  historyRead: (id) => call('history:read', id),
  historySearch: (q) => call('history:search', q),
  historyDelete: (id) => call('history:delete', id),
  historyExport: (id) => call('history:export', id),
  auditExport: (format) => call('audit:export', format),
  auditCount: () => call('audit:count'),
  // processes / links / update
  procList: (tabId) => call('proc:list', tabId),
  procKill: (tabId, pid, signal) => call('proc:kill', { tabId, pid, signal }),
  linkCheck: (values, cwd) => call('link:check', { values, cwd }),
  tabTitle: (id, title) => ipcRenderer.send('tab:title', { id, title }),
  linkOpen: (kind, value, cwd) => call('link:open', { kind, value, cwd }),
  updateCheck: () => call('update:check'),
  onUpdateAvailable: (cb) => on('update:available', cb),
  openExternal: (url) => ipcRenderer.send('open:external', url),
  // misc
  onMenu: (cb) => on('menu:action', cb),
  externalTake: () => call('external:take'),
  onExternal: (cb) => on('external:wake', cb),
  onSysStats: (cb) => on('sys:stats', cb),
  setTheme: (t) => ipcRenderer.send('theme:set', t),
  copy: (t) => ipcRenderer.send('clipboard:write', t),
});
